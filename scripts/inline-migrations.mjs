#!/usr/bin/env node
/**
 * Inline every pkg's drizzle migration SQL into a generated TS file that
 * `compose.ts` imports. This is what makes single-file esbuild bundles
 * work: at runtime there is no `drizzle/` directory next to the bundle,
 * so we cannot `readdirSync(...)` for the migrations. Instead we
 * generate a `src/migrations.generated.ts` for each pkg with a frozen
 * `MIGRATIONS = [{name, sql}, ...]` array; esbuild bundles those
 * strings inline and the runtime applies them from memory.
 *
 * Run automatically by:
 *   - `pnpm bundle` (before esbuild)
 *   - each pkg's `db:generate` script (after drizzle-kit writes new
 *     `.sql` files)
 *
 * Committed to git so dev runs (vitest, `pnpm dev`, etc.) get the
 * same code path as production.
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const PKGS = ["workspace", "session", "task", "catalog"];

for (const pkg of PKGS) {
  const drizzleDir = join(repoRoot, "packages", pkg, "drizzle");
  const outFile = join(repoRoot, "packages", pkg, "src", "migrations.generated.ts");

  let files = [];
  try {
    files = readdirSync(drizzleDir)
      .filter((f) => f.endsWith(".sql"))
      .sort();
  } catch {
    // No drizzle/ dir yet — emit an empty array.
  }

  const entries = files.map((name) => {
    const sql = readFileSync(join(drizzleDir, name), "utf8");
    return { name, sql };
  });

  const header = `// AUTO-GENERATED by scripts/inline-migrations.mjs — DO NOT EDIT BY HAND.
// Regenerate with \`pnpm db:generate\` (per pkg) or \`pnpm bundle\` (whole repo).
// Source of truth: packages/${pkg}/drizzle/*.sql.
// biome-ignore-all format: keep generator output stable across runs.
// biome-ignore-all lint: generated, may include unused/long lines.

`;
  const body = `export interface InlinedMigration {
  readonly name: string;
  readonly sql: string;
}

export const MIGRATIONS: readonly InlinedMigration[] = Object.freeze(${JSON.stringify(entries, null, 2)}) as readonly InlinedMigration[];
`;

  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, header + body, "utf8");
  console.log(
    `inline-migrations: wrote packages/${pkg}/src/migrations.generated.ts (${entries.length} migration${entries.length === 1 ? "" : "s"})`,
  );
}
